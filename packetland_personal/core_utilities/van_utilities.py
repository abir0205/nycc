# VAN pages at 50 items, so this sits well above any real folder or list count.
MAX_VAN_PAGES = 500

def iter_van_pages(url: str, auth: HTTPBasicAuth, context: str, max_pages: int = MAX_VAN_PAGES):
    """
    Yields each page of a paginated VAN response, following 'nextPageLink' until it runs out.

    Once a result set spans more than one page, VAN keeps handing back a nextPageLink
    forever, incrementing $skip past the end of the results and returning empty pages.
    So stop on an empty page rather than trusting the link. The repeated-URL and
    max_pages checks stay as backstops.

    Args:
        url (str): The first page URL to request.
        auth (HTTPBasicAuth): The authentication credentials for the VAN API in this state.
        context (str): Short description of the call, used in error messages.
        max_pages (int, optional): Page ceiling before aborting. Defaults to MAX_VAN_PAGES.
    Yields:
        dict: The parsed JSON body of each page.
    Raises:
        RuntimeError: If pagination repeats a URL or exceeds max_pages.
    """
    seen_urls = set()
    page_count = 0

    while url:
        if url in seen_urls:
            raise RuntimeError(
                f"VAN pagination for {context} repeated page URL `{url}` after "
                f"{page_count} pages. Aborting to avoid an infinite loop."
            )
        seen_urls.add(url)

        page_count += 1
        if page_count > max_pages:
            raise RuntimeError(
                f"VAN pagination for {context} exceeded {max_pages} pages. "
                f"Aborting to avoid an infinite loop."
            )

        response = get_with_retry(url, auth=auth, headers={"accept": "application/json"})
        data = response.json()

        yield data

        # An empty page means we are past the end of the results, whatever nextPageLink claims.
        # Not using the reported 'count' to stop early, since lists can be added or removed
        # mid-walk and a stale count would silently truncate the results.
        if not data.get('items'):
            return

        # VAN returns a full URL string in nextPageLink, or null (which Python parses as None)
        url = data.get('nextPageLink')

