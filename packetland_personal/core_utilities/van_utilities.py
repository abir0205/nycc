def run_async_list_export_job(list_id: int, auth: HTTPBasicAuth) -> str:
    """
    Triggers an asynchronous export job for a saved list ID, returns a Job ID for this export Job
    """
    export_url = "https://api.securevan.com/v4/exportJobs"
    payload = {
        "savedListId": int(list_id),
        "type": 4, # Type 4 maps to saved list pulls I think?
        # NOTE: Webhook is not actually optional, the API website lies.
        "webhookUrl": "<WEBHOOK_URL>"
    }
    headers = {
        "accept": "application/json",
        "content-type": "application/json",
    }
    
    # Trigger Async Export Request
    post_resp = post_with_retry(export_url, json_data=payload, headers=headers, auth=auth)
    post_resp.raise_for_status()
    job_metadata = post_resp.json()
    
    job_id = job_metadata.get("exportJobId")
    print(f"Triggered Export Job {job_id} for Saved List {list_id}")
    return job_id

