def get_van_auth_for_state(secret_dict: dict, state: str, database_mode = "myv") -> HTTPBasicAuth:
    """Resolves basic authentication credentials for a given state from the secret blob"""
    state_upper = state.upper()
    database_mode = validate_database_mode(database_mode)

    if database_mode == DatabaseMode.MyCampaign:
        suffix = 1
    elif database_mode == DatabaseMode.MyVoters:
        suffix = 0
    else:
        raise Exception(f'{database_mode} not a valid db')
    if state_upper not in secret_dict:
        raise ValueError(f"No VAN API credentials configured for state: {state_upper}")

    app_name = secret_dict[state_upper]['app_name']
    app_key = secret_dict[state_upper]['app_key'] + f"|{suffix}"

    return HTTPBasicAuth(app_name, app_key)


