class DatabaseMode(str, Enum):
    MyVoters = "my_v"
    MyCampaign = "my_c"

### -------------------------------------------------------------------------------------------------------------------------------------------- ###

def get_clean_log_context(job_dict, error_msg=None):
    """Helper to dynamically extract log metadata while stripping sensitive auth credentials."""
    sensitive_keys = {"van_auth", "auth", "token", "password", "api_key"}
    context = {k: v for k, v in job_dict.items() if k not in sensitive_keys}
    if error_msg:
        context["error"] = error_msg
    return context

### -------------------------------------------------------------------------------------------------------------------------------------------- ###

def validate_database_mode(database_mode) -> DatabaseMode:
    """
    Validates the Database Mode, handes potential case insensitivity or integer parameters. Returns a standard DatabaseMode Enum.
    """
    if isinstance(database_mode, int):
        if database_mode == 0:
            return DatabaseMode.MyVoters
        if database_mode == 1:
            return DatabaseMode.MyCampaign
        else:
            raise Exception("database_mode must be MyVoters or MyCampaign")
    if database_mode == "" or not database_mode:
        raise Exception("database_mode is a required parameter")
    if database_mode.lower() == "myvoters" or database_mode.lower() == "myv":
        return DatabaseMode.MyVoters
    if database_mode.lower() == "mycampaign" or database_mode.lower() == "myc":
        return DatabaseMode.MyCampaign
    raise Exception("database_mode must be MyVoters or MyCampaign")

