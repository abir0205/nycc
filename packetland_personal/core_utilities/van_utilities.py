def get_async_export_job_status(job_id: str, auth: HTTPBasicAuth) -> str:
    """
    Retrieves the processing status for a specific VAN export job.
    Args:
        job_id (str): The unique identifier of the export job generated by VAN.
        auth (HTTPBasicAuth): The state-level basic authentication credentials 
            associated with the targeted VAN committee context.

    Returns:
        dict: The parsed JSON response containing keys like 'status', 'downloadUrl', 
            and potentially 'errorCode'.
            
    Raises:
        HTTPError: If the VAN API responds with an unhandled non-2xx status code.
    """
    status_url = f"https://api.securevan.com/v4/exportJobs/{job_id}"

    status_resp = get_with_retry(status_url, auth=auth, headers={"accept": "application/json"})
    status_resp.raise_for_status()

    status_data = status_resp.json()
    print(f"Polled status for Job {job_id}: {status_data.get('status')}")
    return status_data


