def poll_async_jobs(
    active_jobs: list,
    check_status_fn,
    on_success_fn,
    success_state: str = "Completed",
    error_state: str = "Error",
    max_timeout_mins: int = 15,
    poll_interval_secs: int = 15
):
    """
    A generic parallel polling engine for async VAN jobs using a generator pattern.

    Args:
        active_jobs (list): List of dicts representing running jobs. Must contain at least an identifier.
        check_status_fn (callable): Function accepting (job_dict) that returns a tuple: (status_str, raw_response_dict)
        on_success_fn (callable): Function accepting (job_dict, raw_response_dict) that handles post-success 
            actions (e.g., downloading files) and returns the processed data payload.
        success_state (str): The string status flag representing a successful job.
        error_state (str): The string status flag representing a failed job upstream.
        max_timeout_mins (int): Maximum global execution time before timing out.
        poll_interval_secs (int): Time to sleep between polling iterations.

    Yields:
        tuple[Any, dict]: The processed payload returned by on_success_fn and the original job dictionary.
    """
    start_time = time.time()
    max_timeout_secs = max_timeout_mins * 60
    failed_jobs = []

    print(f"Beginning parallel polling loop for {len(active_jobs)} active jobs...")

    while active_jobs and (time.time() - start_time) < max_timeout_secs:

        for job in list(active_jobs):
            job_id = job.get("job_id")
            
            try:
                status, status_data = check_status_fn(job)
                if status == success_state:
                    processed_payload = on_success_fn(job, status_data)
                    active_jobs.remove(job)
                    yield processed_payload, job

                # 3. Handle an explicit vendor error status
                elif status == error_state:
                    error_code = status_data.get("errorCode") or status_data.get("error") or "UNKNOWN_ERROR"
                    raise RuntimeError(f"Job reported failure state with code: {error_code}")

                # Note: Unhandled status values (e.g., 'Pending') will just cycle back safely.

            except Exception as job_error:
                print(f"Error encountered for Job {job_id}: {job_error}")
                if job in active_jobs:
                    active_jobs.remove(job)
                
                failed_jobs.append(get_clean_log_context(job, str(job_error)))

        if active_jobs:
            time.sleep(poll_interval_secs)

    # Catch stragglers that timed out
    for timed_out_job in active_jobs:
        failed_jobs.append(get_clean_log_context(
            timed_out_job, 
            f"Job exceeded the max runtime limit of {max_timeout_mins} minutes."
        ))

    if failed_jobs:
        print("\n=== PIPELINE FAILURE LOG SUMMARY ===")
        print(json.dumps(failed_jobs, indent=2))
        raise RuntimeError(f"The async sync pipeline completed with {len(failed_jobs)} errors")

