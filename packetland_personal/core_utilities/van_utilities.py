def export_job_success_handler(job, status_data) -> pd.DataFrame:
    """
    Post-processing for a successful VAN export job. Downloads the exported CSV from the provided download URL and returns a DataFrame.
    Args:
        job (dict): The original job dictionary containing at least the 'job_id' and 'van_auth' for context.
        status_data (dict): The raw status data returned from the VAN API for the completed job.

    Returns:
        pd.DataFrame: The downloaded CSV data as a pandas DataFrame.

    Raises:
        ValueError: If the download URL is missing from the status data.
    """
    download_url = status_data.get("downloadUrl")

    if not download_url:
        raise ValueError("Missing downloadUrl on completed status schema configuration.")
    
    csv_resp = requests.get(download_url)
    csv_resp.raise_for_status()
    return pd.read_csv(StringIO(csv_resp.text), dtype=str)


