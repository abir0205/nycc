def poll_async_export_jobs(active_jobs: list, max_timeout_mins = 15):
    """
    Polls a list of active asynchronous VAN export jobs in parallel using a generator pattern.

    Tracks the status of jobs concurrently. As each job successfully moves to a 
    'Completed' state, its payload is downloaded, converted to a DataFrame, 
    and yielded back to the caller immediately to be appended to our BigQuery table.

    Failed jobs or unhandled API errors are logged defensively and ejected from the active 
    polling queue, safely deferring pipeline exceptions until all other jobs are completed or we timeout.

    Args:
        active_jobs (list): A list of dictionaries containing tracking metadata for active jobs.
            Each dictionary must include: 'job_id', 'list_id', 'list_name', 'cd'.
        max_timeout_mins (int, optional): The maximum time allowed for the global polling loop 
            to execute before timing out stragglers. Defaults to 15.

    Yields:
        tuple[pd.DataFrame, dict]: A tuple containing:
            - pd.DataFrame: The downloaded voter records from the completed list.
            - dict: The original job dictionary

    Raises:
        RuntimeError: A consolidated exception raised at the end of the loop if one 
            or more tracking jobs failed or timed out.
    """
    return poll_async_jobs(
        active_jobs=active_jobs,
        check_status_fn=export_job_status_checker,
        on_success_fn=export_job_success_handler,
        max_timeout_mins=max_timeout_mins
    )

