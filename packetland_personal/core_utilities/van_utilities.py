def refresh_folder_map_regions(folder_id: int, auth: HTTPBasicAuth) -> bool:
    """
    Queues every Map Region in a folder for a refresh. VAN answers immediately;
    fetch_map_regions says when each one finished, by its dateRefreshed moving.

    Args:
        folder_id (int): The unique identifier for the VAN folder.
        auth (HTTPBasicAuth): The authentication credentials for the VAN API in this committee.
    Returns:
        bool: True once VAN has accepted the refresh.
    Raises:
        requests.HTTPError: If VAN refuses the refresh.
    """
    url = f"https://api.securevan.com/v4/folders/{folder_id}/mapRegions/refresh"
    headers = {"Content-Type": "application/json"}

    # Docs say 200, the older automation saw 204. Any 2xx is accepted.
    response = post_with_retry(url, headers = headers, auth = auth)
    response.raise_for_status()

    print(f"Queued the map regions in folder {folder_id} for refresh.")
    return True

