def fetch_folders(auth: HTTPBasicAuth) -> list:
    """
    Retrieves every Folder on the committee.

    Args:
        auth (HTTPBasicAuth): The authentication credentials for the VAN API in this committee.
    Returns:
        list: A list of folder objects, each with a folderId and a name.
    Raises:
        RuntimeError: If VAN pagination fails to terminate.
    """
    url = "https://api.securevan.com/v4/folders"
    all_folders = []

    for data in iter_van_pages(url, auth, context = "folders"):
        all_folders.extend(data.get('items', []))

    print(f"Retrieved {len(all_folders)} folders.")
    return all_folders

