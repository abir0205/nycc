def fetch_map_regions(folder_id: int, auth: HTTPBasicAuth) -> list:
    """
    Retrieves the Map Regions in a Folder, each with its nested mapRoutes.

    Args:
        folder_id (int): The unique identifier for the VAN folder.
        auth (HTTPBasicAuth): The authentication credentials for the VAN API in this committee.
    Returns:
        list: A list of map region objects. A folder with no turf cut returns an empty list.
    Raises:
        RuntimeError: If VAN pagination fails to terminate.
    """
    url = f"https://api.securevan.com/v4/folders/{folder_id}/mapRegions"
    map_regions = []

    for data in iter_van_pages(url, auth, context = f"map regions in folder {folder_id}"):
        map_regions.extend(data.get('items', []))

    return map_regions

